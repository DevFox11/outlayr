const FALLBACK: IconComponent = MoreHorizontalCircle01Icon;

function resolve(name: string | null | undefined): IconComponent {
    return (name ? REGISTRY.get(name) : undefined) ?? FALLBACK;
}

export type CategoryIconType = "stroke" | "solid";

interface CategoryIconProps {
    color: string;
    name: string | null | undefined;
    size?: number;
    /** Ignored for `solid`: the mark is always drawn at the solid weight. */
    strokeWidth?: number;
    type?: CategoryIconType;
}

export function CategoryIcon({ name, color, size = 18, type = "solid", strokeWidth = 1.8 }: CategoryIconProps) {
    const glyph = resolve(name);
    const solid = type === "solid";
    return <Icon color={color} icon={glyph} size={size} strokeWidth={solid ? SOLID_STROKE : strokeWidth} />;
}
