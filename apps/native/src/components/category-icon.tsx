/** Registry keys offered by the category icon picker, in display order. */
export const CATEGORY_ICON_NAMES = Object.keys(REGISTRY);

const FALLBACK: IconPair = REGISTRY.MoreHorizontalCircle01;

function resolve(name: string | null | undefined): IconPair {
	if (name && REGISTRY[name]) {
		return REGISTRY[name];
	}
	return FALLBACK;
}

export type CategoryIconType = "stroke" | "solid";

interface CategoryIconProps {
	name: string | null | undefined;
	color: string;
	size?: number;
	type?: CategoryIconType;
	/**
	 * Ignored when `type` is `solid`: a solid glyph is a filled path with no
	 * outline to widen, so a stroke width only thickens its edges into mush.
	 */
	strokeWidth?: number;
}

export function CategoryIcon({
	name,
	color,
	size = 18,
	type = "solid",
	strokeWidth = 1.8,
}: CategoryIconProps) {
	const pair = resolve(name);
	const solid = type === "solid";
	return (
		<HugeiconsIcon
			color={color}
			icon={solid ? pair.solid : pair.stroke}
			size={size}
			strokeWidth={solid ? undefined : strokeWidth}
		/>
	);
}
